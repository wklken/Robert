"""Render both stage-3 snapshots from the exact same fourteen stored inputs.

Run from repository root:
    PYTHONPATH=src .venv/bin/python docs/reviews/2026-10-29-worker-contract-prompts/render-stage-3.py

The archived before renderer is evidence, never imported by production. Runtime
paths remain exactly those supplied by inputs.json in both renders; real attempt
path materialization is covered separately by tests.test_attempt_context.
"""
import hashlib
import json
from pathlib import Path
import runpy

from robert_agent.render_prompt import render_prompt

root = Path(__file__).resolve().parent
input_path = root.parent / '2026-10-29-worker-prompts/inputs.json'
inputs = json.loads(input_path.read_text())
before = runpy.run_path(str(root / 'stage-3-renderer-before.py'))['render_prompt']
for stage, renderer in [('before', before), ('after', render_prompt)]:
    text = f'# Stage 3 {stage}: same 14 inputs\n\n'
    text += f'Input SHA256: `{hashlib.sha256(input_path.read_bytes()).hexdigest()}`. '
    text += 'Generated by `render-stage-3.py`; runtime paths are unchanged sample inputs.\n\n'
    for sample in inputs:
        prompt = renderer(sample['task'], sample['route_result'], sample['events'],
            sample.get('runtime_context'), sample.get('project_memories'), sample.get('runtime_knowledge'))
        text += '## ' + sample['name'] + '\n\n````text\n' + prompt + '````\n\n'
    (root / f'stage-3-{stage}.md').write_text(text)
