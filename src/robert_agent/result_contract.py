"""The sole worker submission contract and deterministic result normalization."""
from copy import deepcopy
import hashlib
import json
import re

CONTRACT_ID = "compact-v1"
NORMALIZER_VERSION = 1
OUTPUTS = {"classification_result", "local_result", "comment_analysis", "new_pr", "update_existing_pr",
           "review_comment", "pr_review_comment", "waiting_for_user", "multi_agent_review_report", "multi_agent_vote_report"}
FIELDS = {"planned_github_actions", "used_skills", "verification", "consumed_event_fingerprints",
          "consumed_work_item_event_ids", "handoff", "memory_delta", "used_memory_ids", "recommended_route",
          "branch_slug", "review_point_evaluation", "review_input_kind", "operator_question", "remediation_evidence"}
ACTION_FIELDS = {"comment": {"type", "body", "target_url"}, "push_existing_pr": {"type"},
                 "open_pr": {"type", "title", "body", "issue_resolution", "remaining_scope", "target_url"},
                 "submit_pr_review": {"type", "body", "target_url"}}
CONTROL_MARKER = re.compile(r"<!--\s*(?:robert|dd)-(?:comment|workstream)\b", re.I)
ISSUE_REFERENCE = re.compile(r"(?i)\b(?:close(?:s|d)?|fix(?:es|ed)?|resolve(?:s|d)?|refs?)\s*:?[ \t]+(?:[\w.-]+/[\w.-]+)?(?:#\d+\b|https?://github\.com/[^\s]+)")


class InvalidSubmission(ValueError):
    def __init__(self, field, message, code="invalid_submission"):
        super().__init__(message)
        self.field, self.code = field, code

    def response(self):
        return {"ok": False, "status": "failed_validation", "reason_code": self.code,
                "field_path": self.field, "safe_error": str(self),
                "required_action": "Correct the indicated field and submit again in this attempt."}


def _require(condition, field, message, code="invalid_submission"):
    if not condition:
        raise InvalidSubmission(field, message, code)


def validate_submission(submission, output_type, origin_type):
    _require(output_type in OUTPUTS, "output_type", "Unsupported output type.")
    _require(isinstance(submission, dict), "result", "Submission must be an object.")
    unknown = set(submission) - FIELDS
    _require(not unknown, "result", "Submission contains unsupported or program-owned fields.", "program_owned_field")
    consumed = "consumed_work_item_event_ids" if origin_type == "web" else "consumed_event_fingerprints"
    for field in ("planned_github_actions", "used_skills", "verification", consumed):
        _require(field in submission and isinstance(submission[field], list), field, field + " is a required list.")
    for field in ("used_skills", "consumed_event_fingerprints", "consumed_work_item_event_ids", "used_memory_ids"):
        if field in submission:
            _require(isinstance(submission[field], list) and all(isinstance(v, str) and v for v in submission[field]), field, field + " must contain non-empty strings.")
    for field in ("handoff", "recommended_route", "branch_slug"):
        if field in submission:
            _require(isinstance(submission[field], str), field, field + " must be a string.")
    for index, action in enumerate(submission["planned_github_actions"]):
        field = f"planned_github_actions[{index}]"
        _require(isinstance(action, dict) and isinstance(action.get("type"), str) and action["type"] in ACTION_FIELDS, field + ".type", "Action type is unsupported.")
        _require(not (set(action) - ACTION_FIELDS[action["type"]]), field, "Action contains unsupported or program-owned fields.", "program_owned_field")
        for name in set(action) - {"type"}:
            _require(isinstance(action[name], str) and bool(action[name].strip()), field + "." + name, "Action field must be a non-empty string.")
        if action["type"] in {"comment", "open_pr", "submit_pr_review"}:
            _require(bool(action.get("body", "").strip()), field + ".body", "Action body is required.")
            # Native registered reports are verified byte-for-byte by their own auditor.
            if output_type != "multi_agent_vote_report":
                _require(not CONTROL_MARKER.search(action["body"]), field + ".body", "Control markers are generated by Robert.", "program_owned_marker")
        if action["type"] == "open_pr":
            _require(bool(action.get("title", "").strip()), field + ".title", "PR title is required.")
    types = [action["type"] for action in submission["planned_github_actions"]]
    if output_type in {"classification_result", "local_result"}:
        _require(not types, "planned_github_actions", "This output requires an empty action list.")
    if output_type == "pr_review_comment":
        _require(types == ["comment"], "planned_github_actions", "A PR review requires exactly one comment.")
    if output_type == "waiting_for_user":
        _require(not types if origin_type == "web" else bool(types) and all(kind == "comment" for kind in types), "planned_github_actions", "Waiting requires only deliverable question comments; Web waiting has no publication actions.")
    if "operator_question" in submission:
        from robert_agent import audit_result
        question = submission["operator_question"]
        _require(isinstance(question, dict) and not (set(question) - {"kind", "summary", "choices"}), "operator_question", "Question contains unsupported fields.")
        _require(isinstance(question.get("kind"), str), "operator_question.kind", "Question kind must be a string.")
        for choice in question.get("choices", []) if isinstance(question.get("choices", []), list) else []:
            _require(isinstance(choice, dict) and not (set(choice) - {"id", "label"}), "operator_question.choices", "Choice contains unsupported fields.")
        question_error = audit_result._audit_operator_question(submission)
        _require(question_error is None, "operator_question", question_error or "Invalid operator question.")
    if "review_input_kind" in submission:
        _require(isinstance(submission["review_input_kind"], str) and submission["review_input_kind"] in {"request", "review_feedback", "mixed"}, "review_input_kind", "Review input kind is invalid.")
    if "review_point_evaluation" in submission:
        evaluation = submission["review_point_evaluation"]
        _require(isinstance(evaluation, list) and all(isinstance(item, dict) and all(isinstance(item.get(field), str) and bool(item[field].strip()) for field in ("summary", "verdict", "reasoning", "action")) for item in evaluation), "review_point_evaluation", "Review evaluation entries require summary, verdict, reasoning and action.")
        from robert_agent import audit_result
        for index, item in enumerate(evaluation):
            field = f"review_point_evaluation[{index}]"
            _require(set(item) == {"summary", "verdict", "reasoning", "action"}, field, "Review evaluation contains unsupported fields.")
            _require(item["verdict"] in audit_result.VALID_REVIEW_VERDICTS, field + ".verdict", "Review verdict is invalid.")
            _require(item["action"] in audit_result.VALID_REVIEW_ACTIONS, field + ".action", "Review action is invalid.")
            _require(item["action"] != "implement" or item["verdict"] in audit_result.IMPLEMENTABLE_VERDICTS, field + ".action", "Implement requires a supported verdict.")
    if "memory_delta" in submission:
        memory = submission["memory_delta"]
        _require(isinstance(memory, dict), "memory_delta", "Memory delta must be an object.")
        for name in ("status", "reason"):
            _require(name not in memory or isinstance(memory[name], str), "memory_delta." + name, "Memory field must be a string.")
        _require("entries" not in memory or (isinstance(memory["entries"], list) and all(isinstance(item, dict) for item in memory["entries"])), "memory_delta.entries", "Memory entries must be objects.")
    for index, entry in enumerate(submission["verification"]):
        field = f"verification[{index}]"
        _require(isinstance(entry, dict), field, "Verification entry must be an object.")
        allowed = {"command", "status", "purpose", "required", "exit_code", "skipped_reason", "source", "command_record_path", "url"}
        _require(not (set(entry) - allowed), field, "Verification contains unsupported fields.")
        for name in ("command", "status", "purpose", "required", "source"):
            _require(name in entry, field + "." + name, "Verification field is required: " + name)
        command = entry["command"]
        _require((isinstance(command, str) and bool(command.strip())) or (isinstance(command, list) and bool(command) and all(isinstance(arg, str) and bool(arg) for arg in command)), field + ".command", "Verification command must be non-empty text or an argument list.")
        _require(isinstance(entry["status"], str) and entry["status"] in {"passed", "failed", "skipped"}, field + ".status", "Verification status is invalid.")
        _require(isinstance(entry["purpose"], str) and bool(entry["purpose"].strip()), field + ".purpose", "Verification purpose is required.")
        _require(type(entry["required"]) is bool, field + ".required", "Verification required must be a boolean.")
        if entry["status"] == "skipped":
            _require(isinstance(entry.get("skipped_reason"), str) and bool(entry["skipped_reason"].strip()), field + ".skipped_reason", "Skipped verification requires a reason.")
            _require("exit_code" not in entry, field + ".exit_code", "Skipped verification cannot claim an execution exit code.")
        _require(isinstance(entry["source"], str) and entry["source"] in {"worker_reported", "runtime_recorded", "external_ci"}, field + ".source", "Verification source is invalid.")
        if entry["status"] != "skipped":
            _require(type(entry.get("exit_code")) is int, field + ".exit_code", "Executed verification requires an exit code.")
            _require((entry["status"] == "passed") == (entry["exit_code"] == 0), field + ".exit_code", "Verification status and exit code disagree.")
        if entry["source"] == "runtime_recorded":
            _require(isinstance(entry.get("command_record_path"), str) and bool(entry["command_record_path"]), field + ".command_record_path", "Runtime evidence requires its command journal path.")
        if entry["source"] == "external_ci":
            _require(isinstance(entry.get("url"), str) and entry["url"].startswith("https://"), field + ".url", "CI evidence requires its HTTPS run URL.")
    evidence = submission.get("remediation_evidence")
    if evidence is not None:
        _require(isinstance(evidence, dict) and set(evidence) == {"resolution_summary"} and isinstance(evidence["resolution_summary"], str) and bool(evidence["resolution_summary"].strip()), "remediation_evidence", "Provide only a non-empty resolution_summary; Robert binds the episode.")
    return submission


def semantic_fingerprint(envelope):
    data = {"contract": CONTRACT_ID, "task_id": envelope["task_id"], "attempt_id": envelope["attempt_id"],
            "output_type": envelope["output_type"], "submission": envelope["submission"]}
    return hashlib.sha256(json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def comment_marker(task_id, attempt_id, index):
    return f"<!-- robert-comment task_id={task_id} attempt_id={attempt_id} action_index={index} -->"


def _target(action, scope, index):
    candidates = {f"https://github.com/{scope['repo']}/{'issues' if item['source_type'] == 'issue' else 'pull'}/{item['number']}"
                  for item in scope.get("sources", []) if item.get("source_type") in {"issue", "pull_request"}}
    target = action.get("target_url")
    if target is None:
        _require(len(candidates) == 1, f"planned_github_actions[{index}].target_url", "Select target_url explicitly when the task has multiple or no publication targets.", "ambiguous_target")
        return next(iter(candidates))
    _require(target in candidates, f"planned_github_actions[{index}].target_url", "Target is outside the task's allowed sources.", "action_scope")
    return target


def normalize(envelope, settings):
    submission = envelope["submission"]
    validate_submission(submission, envelope["output_type"], settings["origin_type"])
    output_type = envelope["output_type"]
    scope = settings["action_scope"]
    result = deepcopy(submission)
    result.update({key: envelope[key] for key in ("task_id", "attempt_id", "output_type")})
    result.setdefault("consumed_event_fingerprints", [])
    result.setdefault("consumed_work_item_event_ids", [])
    for index, action in enumerate(result["planned_github_actions"]):
        field = f"planned_github_actions[{index}]"
        kind = action["type"]
        if kind == "push_existing_pr":
            for source, target in (("worktree_path", "worktree_path"), ("branch_name", "branch"), ("remote", "remote")):
                _require(bool(scope.get(source)), field, "Assigned push target is unavailable.")
                action[target] = scope[source]
        elif kind in {"comment", "submit_pr_review"}:
            action["target_url"] = _target(action, scope, index)
            if output_type == "multi_agent_vote_report":
                for name in ("vote_round_id", "vote_snapshot_id", "vote_report_path", "vote_report_sha256"):
                    _require(bool(scope.get(name)), field, "Registered vote report is unavailable.")
                    action[name] = scope[name]
                _require(comment_marker(envelope["task_id"], envelope["attempt_id"], index) in action["body"], field + ".body", "Registered vote report requires its generated action marker.")
            elif kind == "submit_pr_review":
                for target, source in {"round_id": "review_round_id", "commit_id": "review_head_sha", "base_sha": "review_base_sha", "base_ref": "review_base_ref", "report_path": "review_report_path", "report_sha256": "review_report_sha256"}.items():
                    _require(bool(scope.get(source)), field, "Registered review report is unavailable.")
                    action[target] = scope[source]
            else:
                if output_type == "pr_review_comment":
                    login = scope.get("pr_authors", {}).get(action["target_url"])
                    _require(isinstance(login, str) and bool(re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})", login)), field + ".body", "Trusted PR author is unavailable.")
                    action["pr_author_login"] = login
                    action["body"] = f"@{login}\n\n" + action["body"]
                action["body"] += "\n\n" + comment_marker(envelope["task_id"], envelope["attempt_id"], index)
        elif kind == "open_pr":
            for source in ("repo", "branch_name", "base_branch"):
                _require(bool(scope.get(source)), field, "Assigned PR target is unavailable.")
            action.update(repo=scope["repo"], head=scope["branch_name"], base=scope["base_branch"])
            issues = [item["number"] for item in scope.get("sources", []) if item.get("source_type") == "issue"]
            issue = None
            if "target_url" in action:
                selected = _target(action, scope, index)
                _require("/issues/" in selected, field + ".target_url", "Select the source issue for this PR.")
            if issues:
                if len(issues) == 1 and "target_url" not in action:
                    issue = issues[0]
                else:
                    selected = _target(action, scope, index)
                    _require("/issues/" in selected, field + ".target_url", "Select the source issue for this PR.")
                    issue = int(selected.rsplit("/", 1)[1])
                _require(action.get("issue_resolution") in {"complete", "partial"}, field + ".issue_resolution", "Select complete or partial issue resolution.")
                _require(not ISSUE_REFERENCE.search(action["body"]), field + ".body", "Robert generates the issue reference; remove supplied closing/reference statements.")
                if action["issue_resolution"] == "partial":
                    _require(bool(action.get("remaining_scope", "").strip()), field + ".remaining_scope", "Partial delivery requires remaining_scope.")
                action["body"] += f"\n\n{'Fixes' if action['issue_resolution'] == 'complete' else 'Refs'} #{issue}"
                action.pop("target_url", None)
            action["body"] += f"\n\n<!-- robert-workstream\norigin_workstream_id: {scope['workstream_id']}\nsource_issue: {issue or ''}\ntask_id: {envelope['task_id']}\ncreated_by: robert\n-->"
    if "remediation_evidence" in result:
        episode = settings.get("remediation_context") or {}
        evidence = result["remediation_evidence"]
        for name in ("episode_id", "observed_head_sha", "observed_base_sha"):
            evidence[name] = episode.get(name)
        evidence["kind"] = episode.get("episode_kind")
        if settings["task_kind"] == "ci_remediation":
            evidence["failure_signature"] = episode.get("failure_signature")
    # Source labels are declarations; only controller/independent audits can attest.
    for entry in result["verification"]:
        entry["attested"] = False
    return result
